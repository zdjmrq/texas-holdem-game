//! WebSocket protocol v2 wire types for the authoritative poker room server.
//!
//! Wire compatibility with the reference JavaScript implementation
//! (`server/local-server.js`, `js/network.js` at commit `e0c6c6f`, v1.5.8) is a
//! hard requirement: a Rust server must be able to serve the old JS desktop
//! client and a Rust client must be able to talk to the old JS server. Field
//! names, JSON value types, message types, error codes, error texts, close
//! codes and whitelists are therefore pinned by golden corpora captured from
//! the real reference server:
//!
//! * `tests/golden/protocol/s2c-messages.jsonl` — every server→client message.
//! * `tests/golden/protocol/c2s-messages.jsonl` — every client→server message.
//! * `tests/golden/protocol/parse-errors.jsonl` — raw payload to exact error.
//! * `tests/golden/protocol/config-cases.jsonl` / `name-cases.jsonl` —
//!   room-config whitelisting and player-name normalisation.
//! * `tests/golden/protocol/server-constants.json`, `client-behaviour.json`,
//!   `close-events.jsonl`, `hello-probe-cases.jsonl`.
//!
//! The corpora are regenerated by `node oracle/golden-protocol.js` from the
//! read-only reference repository.
//!
//! # Wire conventions
//!
//! * Every message is a JSON object with a `type` string.
//! * Every message on the wire carries `"protocolVersion": 2`. Server messages
//!   always include it; client messages are accepted without it and with any
//!   value that JavaScript's `Number(...)` conversion maps to `2`.
//! * Server messages are serialised with the `protocolVersion` field first and
//!   then the tag and payload; key order is irrelevant on the wire.
//! * Hidden information never appears in `game_state`: opponents' hole cards
//!   are only revealed inside `lastHandResult.results[].cards` at showdown.
//!
//! # Parsing strictness
//!
//! The reference JS server is very permissive (it relies on `Number()` /
//! `String()` coercion everywhere). [`parse_client_message`] reproduces the JS
//! validation *order* and *messages* exactly, but the typed DTOs reject
//! non-conforming JSON value types with a generic `INVALID_REQUEST` error
//! instead of silently coercing them. The old JS client only sends conforming
//! JSON, so cross-implementation compatibility is unaffected; the difference is
//! documented in `docs/specs/protocol-v2.md`.
