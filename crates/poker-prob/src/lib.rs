//! Equity, outs, exact enumeration and Monte Carlo analysis for Texas hold'em
//! and 6+ short deck.
//!
//! The crate is a faithful Rust port of `js/probability-core.js` from the
//! original v1.5.8 JavaScript project:
//!
//! * [`prepare`] mirrors `prepare(options)`: input validation, deck order and
//!   opponent clamping.
//! * [`exact_heads_up`] mirrors `exactHeadsUp(prepared)`.
//! * [`monte_carlo`] mirrors `monteCarlo(prepared, options)`; the deterministic
//!   sample count replaces the JS time budget (see [`MonteCarloOptions`]).
//! * [`calculate`] mirrors `calculate(options)` and attaches the outs report.
//! * [`find_improvements`] mirrors `findImprovements(...)`.
//!
//! Randomness is injected through [`poker_core::XorShift32Rng`], which
//! reproduces the original JS `hashSeed` + `xorshift32` stream bit for bit, and
//! the partial Fisher-Yates draw order is identical to the JS implementation.
//! With a fixed seed the Rust Monte Carlo samples are therefore identical to
//! the JS samples, not merely statistically equivalent. The golden corpus in
//! `tests/golden/prob/` pins this down for both variants; it is generated by
//! `oracle/golden-equity.js` and checked by `tests/js_golden_prob.rs`.
//!
//! All numeric results use `f64`, matching the JavaScript implementation. Note
//! that the JS `elapsedMs` field is a wall-clock reading: [`EquityResult`]
//! carries its own `elapsed_ms` for diagnostics, but it is deliberately not
//! part of the deterministic contract or of [`EquityResult`] equality.
#![forbid(unsafe_code)]
#![warn(missing_docs)]

